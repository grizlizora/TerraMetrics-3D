/**
 * Resolves country name in Ukrainian by ISO code or fallback English name
 */
export function getCountryNameUk(iso: string, englishName?: string): string | undefined {
  if (iso && COUNTRY_NAMES_UK[iso]) {
    return COUNTRY_NAMES_UK[iso];
  }
  if (englishName && SPECIAL_TERRITORIES_UK[englishName]) {
    return SPECIAL_TERRITORIES_UK[englishName];
  }
  return undefined;
}
